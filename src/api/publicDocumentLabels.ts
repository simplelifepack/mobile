export function publicDocumentLabels(values: string[]) {
  return [...new Set(values.flatMap(value => {
    const key = value.trim().toLowerCase().replace(/[ -]+/g, '_');
    const label = aliases[key] ?? key;
    return publicLabels.has(label) ? [label] : [];
  }))];
}